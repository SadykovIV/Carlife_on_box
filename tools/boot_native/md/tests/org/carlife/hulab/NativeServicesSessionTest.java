package org.carlife.hulab;

import java.io.*;
import java.lang.reflect.Field;
import java.util.*;
import java.util.concurrent.TimeUnit;

/** Android producer boundary injected; real native dispatch, writer and lifecycle. */
public final class NativeServicesSessionTest {
    static int checks;
    static void check(boolean ok,String why){checks++;if(!ok)throw new AssertionError(why);}
    static NativeServiceState state(NativeServices s)throws Exception {Field f=NativeServices.class.getDeclaredField("wire");f.setAccessible(true);return (NativeServiceState)f.get(s);}
    static List<MdMain.Frame> frames(NativeVideoFlowTest.Transport t)throws Exception{List<MdMain.Frame> f=new ArrayList<MdMain.Frame>();synchronized(t.writes){for(byte[] b:t.writes)f.add(NativeVideoFlowTest.read(b));}return f;}
    static boolean has(NativeVideoFlowTest.Transport t,int id)throws Exception{for(MdMain.Frame f:frames(t))if(f.id==id)return true;return false;}
    static void await(NativeVideoFlowTest.Transport t,int id)throws Exception{long end=System.nanoTime()+TimeUnit.SECONDS.toNanos(2);while(!has(t,id)&&System.nanoTime()<end)Thread.sleep(2);check(has(t,id),"writer delivers "+Integer.toHexString(id));}
    public static void main(String[] args)throws Exception{
        MdMain.audioSource="off";MdMain.nativeServicesEnabled=false;MdMain.videoSource="mediacodec";
        NativeVideoFlowTest.Transport t=new NativeVideoFlowTest.Transport();final MdMain.Session session=new MdMain.Session(t);
        NativeServices services=new NativeServices(null);NativeServiceState source=state(services);
        NativeVideoFlowTest.ready(session);session.services=services;
        try{
            byte[] subscription=MdWireTest.hex("08021202080012020802");
            session.dispatch(1,0x18043,subscription);check(session.controls.isEmpty(),"no unsupported ACK before actual producer capability");
            source.capabilities(true,true);session.dispatch(1,0x18045,subscription);
            source.media("player","Title","Artist","Album","id",120000,1,true,5000,new byte[0]);
            source.route(YandexNotificationRoute.parse("ru.yandex.yandexnavi","Через 200 м поверните направо","",""));
            session.writer=new Thread(new Runnable(){public void run(){session.writeLoop();}});session.writer.start();
            await(t,0x10044);await(t,0x10035);await(t,0x10030);
            check(session.routeNavigationActive&&session.naviWireActive,"NAVI status tracks real producer state");
            session.dispatch(1,0x1800a,new byte[0]);check(session.services==services,"video PAUSE preserves services");
            session.dispatch(1,0x18001,MdMain.Proto.ints(1,2,2,0));
            check(session.services==null&&!session.routeNavigationActive,"new logical VERSION retires old producers");
            source.route(YandexNotificationRoute.parse("ru.yandex.yandexnavi","Через 100 м поверните налево","",""));
            check(source.poll()==null,"closed producer cannot queue stale route");
            check(session.open,"metadata and lifecycle do not terminate native session");
        }finally{session.close();if(session.writer!=null)session.writer.join(1000);}
        check(session.writer==null||!session.writer.isAlive(),"writer retired after close");
        // Snapshot is regenerated by the writer, not frozen while blocked behind old I/O.
        NativeVideoFlowTest.Transport snapshot=new NativeVideoFlowTest.Transport();final MdMain.Session current=new MdMain.Session(snapshot);
        NativeVideoFlowTest.ready(current);current.moduleStatusDue=1;current.nativeProgress();
        current.audioWireActive=true;current.audioHuMuted=true;
        current.speechWireActive=true;
        current.services=new NativeServices(null);
        Field voiceField=NativeServices.class.getDeclaredField("voice");voiceField.setAccessible(true);Object voice=voiceField.get(current.services);
        Field activeField=NativeVoice.class.getDeclaredField("active");activeField.setAccessible(true);activeField.setBoolean(voice,true);
        try{current.writer=new Thread(new Runnable(){public void run(){current.writeLoop();}});current.writer.start();await(snapshot,0x10026);
            check(Arrays.equals(frames(snapshot).get(0).payload,NativeSessionProtocol.initialModules(true,false,true)),"late snapshot sees current TTS/VR and muted MEDIA");
        }finally{current.close();if(current.writer!=null)current.writer.join(1000);}
        System.out.println("PASS "+checks+" real native services/writer/boundary checks; Android producers injected");
    }
}
